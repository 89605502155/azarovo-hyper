"""Interfaces the application layer depends on.

The libvirt adapter implements them for real hypervisors; the test-suite has an
in-memory implementation. Nothing above this layer imports ``libvirt``.
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Protocol, runtime_checkable

from azarovo_hyper.domain.resources import HostUsage
from azarovo_hyper.domain.state import VMState
from azarovo_hyper.domain.stats import HostInfo


@runtime_checkable
class Domain(Protocol):
    """One defined virtual machine on a hypervisor connection."""

    @property
    def name(self) -> str: ...
    @property
    def uuid(self) -> str: ...

    def state(self) -> VMState: ...
    def start(self) -> None: ...
    def shutdown(self) -> None: ...
    def destroy(self) -> None: ...
    def reboot(self) -> None: ...
    def reset(self) -> None: ...
    def suspend(self) -> None: ...
    def resume(self) -> None: ...
    def undefine(self) -> None: ...
    def xml(self, *, inactive: bool = False) -> str: ...

    def autostart(self) -> bool: ...
    def set_autostart(self, enabled: bool) -> None: ...

    def max_memory_kib(self) -> int: ...
    def set_memory(self, kib: int, *, live: bool, config: bool) -> None: ...
    def set_max_memory(self, kib: int, *, live: bool, config: bool) -> None: ...
    def memory_stats(self) -> dict[str, int]: ...
    def set_stats_period(self, seconds: int, *, live: bool, config: bool) -> None: ...

    def vcpus(self) -> int: ...
    def set_vcpus(self, count: int, *, live: bool, config: bool) -> None: ...
    def cpu_time_ns(self) -> int: ...

    def attach(self, xml: str, *, live: bool, config: bool) -> None: ...
    def detach(self, xml: str, *, live: bool, config: bool) -> None: ...
    def update_device(self, xml: str, *, live: bool, config: bool) -> None: ...
    def block_stats(self, device: str) -> tuple[int, int, int, int, int]: ...
    def interface_stats(self, device: str) -> tuple[int, ...]: ...
    def addresses(self) -> dict[str, list[str]]: ...

    def screenshot(self, screen: int = 0) -> tuple[str, bytes]: ...
    def snapshot_create(self, xml: str) -> None: ...
    def snapshot_names(self) -> list[str]: ...
    def snapshot_revert(self, name: str) -> None: ...
    def snapshot_delete(self, name: str) -> None: ...


@runtime_checkable
class Connection(Protocol):
    """An open connection to one hypervisor URI. Must be thread-safe."""

    @property
    def uri(self) -> str: ...

    def define(self, xml: str) -> Domain: ...
    def lookup(self, name: str) -> Domain: ...
    def names(self) -> list[str]: ...
    def host_info(self) -> HostInfo: ...
    def usage(self) -> HostUsage: ...
    def is_alive(self) -> bool: ...
    def close(self) -> None: ...


Connector = Callable[[str], Connection]
"""Opens a :class:`Connection` for a URI."""


@runtime_checkable
class DiskTool(Protocol):
    """Creates and removes disk images."""

    def create(
        self, path: Path, size_mib: int, fmt: str = "qcow2", preallocation: str = "off"
    ) -> bool: ...
    def remove(self, path: Path) -> bool: ...
